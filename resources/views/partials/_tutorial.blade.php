    <h3 class="text-lg font-semibold mb-4 text-gray-100 dark:text-white border-b border-slate-600 pb-2">Cara Menggunakan Konverter</h3>
    <ol class="list-decimal list-inside space-y-3 text-sm text-gray-300 dark:text-gray-300">
        <li>
            <strong>Pilih File Anda:</strong> Klik <strong class="text-indigo-400">"Pilih File"</strong>. Pilih dokumen, gambar, audio, atau video yang ingin Anda konversi dari perangkat Anda.
        </li>
        <li>
            <strong>Tentukan Format Output:</strong> Klik menu dropdown <strong class="text-indigo-400">"Pilih Format Output"</strong> dan pilih format file tujuan yang Anda inginkan.
        </li>
        <li>
            <strong>Mulai Konversi:</strong> Tekan tombol <strong class="text-indigo-400">"Konversi File"</strong>. Proses akan berjalan di server kami. Mohon tunggu sebentar.
        </li>
        <li>
            <strong>Unduh Hasilnya:</strong> Jika berhasil, pesan sukses dan link unduhan akan muncul di bagian atas. Klik link tersebut untuk menyimpan file baru Anda.
        </li>
    </ol>
    <p class="mt-5 text-xs text-gray-500 dark:text-gray-500 border-t border-slate-700 pt-3">
        Catatan: Hasil konversi mungkin bervariasi. File Anda diproses secara aman dan dihapus dari server kami setelah beberapa saat.
    </p>
